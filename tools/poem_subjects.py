RX = {k: re.compile(v[2]) for k, v in F.items()}


def plain_pad(pad):
    return re.sub(r'\*\*', '', pad or '')


def features(poem, heading=''):
    """Count every feature in the poem lines, its பதவுரை and (weakly) the sub-heading above it."""
    lines = ' '.join(poem['lines'])
    pad = plain_pad(poem.get('pad', ''))
    notes = ' '.join(n.get('p', '') for n in poem.get('notes', [])[:1])
    sc = {}
    for k, rx in RX.items():
        v = len(rx.findall(lines)) * 1.0 + len(rx.findall(pad)) * 1.0 + len(rx.findall(heading)) * 1.5 + len(rx.findall(notes)) * 0.25
        if v:
            sc[k] = v
    return sc


def label(key):
    return F[key][1]


def kind(key):
    return F[key][0]
